-- ============================================================ AUTH / USERS
CREATE TABLE IF NOT EXISTS roles (
    id TEXT PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    description TEXT,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    discount_cap INTEGER NOT NULL DEFAULT 0 CHECK (discount_cap BETWEEN 0 AND 100),
    -- Whether staff with this role can be assigned as the attending vet
    -- (Appointments grid, New Visit, Grooming, Inpatient) — a role
    -- attribute rather than a hardcoded role NAME check, so renaming or
    -- restructuring the "Vet" role can't silently empty every vet picker.
    is_vet_role BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TEXT NOT NULL
);

-- Static seed list of every permission key the app understands — not
-- admin-editable itself, just the fixed vocabulary of what *can* be gated.
-- Kept in sync with auth.PERMISSIONS on every launch.
CREATE TABLE IF NOT EXISTS permissions (
    id TEXT PRIMARY KEY,
    label TEXT NOT NULL,
    category TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id TEXT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id TEXT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    role_id TEXT NOT NULL REFERENCES roles(id),
    custom_discount_cap INTEGER CHECK (custom_discount_cap BETWEEN 0 AND 100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    -- Bumped every time this user's password_hash changes (self-service or
    -- admin reset). Stashed in the session at login and compared on every
    -- request (see require_login() in app.py) — a session logged in before
    -- the most recent change is invalidated, so a stolen cookie stops
    -- working the moment the password it was issued under is replaced,
    -- instead of staying valid for the rest of its normal lifetime.
    password_changed_at TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role_id);

CREATE TABLE IF NOT EXISTS login_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    username TEXT,
    success INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    ip TEXT,
    user_agent TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    username TEXT,
    timestamp TEXT NOT NULL,
    action TEXT NOT NULL,          -- 'create' / 'update' / 'delete'
