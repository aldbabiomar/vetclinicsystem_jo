-- ============================================================ POINT OF SALE (Retail only)
CREATE TABLE IF NOT EXISTS sales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date TEXT NOT NULL,  -- actually a full timestamp (datetime.now().isoformat()), not date-only -- see note in data_integrity_framework.md
    cashier_id TEXT,
    subtotal NUMERIC(12,3) NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
    discount_applied_by TEXT,
    total NUMERIC(12,3) NOT NULL,
    payment_method TEXT,
    -- Cash payment method only — what the customer actually handed over
    -- and what was handed back, for the cashier's own reconciliation.
    -- Optional: NULL for non-cash sales, and NULL for cash too if the
    -- cashier didn't bother entering it.
    cash_received NUMERIC(12,3),
    change_given NUMERIC(12,3),
    -- One-time token generated fresh each time the POS page loads (see
    -- pos_page()/pos.html), submitted back with the checkout POST. A
    -- double-click ("Complete Sale" clicked twice on the same unchanged
    -- cart) previously created two separate, fully valid sales — no
    -- confirmation prompt either side, nothing tying the two submissions
    -- together. pos_checkout() checks for an existing sale with this key
    -- before inserting a new one; NULL for any sale that predates this
    -- column (never collides — see idx_sales_idempotency_key below).
    idempotency_key TEXT,
    FOREIGN KEY (cashier_id) REFERENCES users(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_sales_idempotency_key ON sales(idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS sale_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id INTEGER NOT NULL,
    item_id TEXT NOT NULL,
    quantity NUMERIC(10,3) NOT NULL,
    unit_price NUMERIC(12,3) NOT NULL,
    line_total NUMERIC(12,3) NOT NULL,
    -- Cost snapshotted at sale time — this is what lets COGS reporting
    -- reflect the actual cost basis of each sale instead of re-reading
    -- current inventory cost (which would retroactively change a past
    -- month's COGS every time an item's cost is edited). Nullable: an
    -- item without a cost_price set has nothing to snapshot.
    unit_cost NUMERIC(12,3),
    FOREIGN KEY (sale_id) REFERENCES sales(id),
    FOREIGN KEY (item_id) REFERENCES inventory_list(id)
);
CREATE INDEX IF NOT EXISTS idx_saleitems_sale ON sale_items(sale_id);

-- ============================================================ REFUNDS (Admin only)
-- Two kinds: 'retail' (one or more products returned, identified by barcode,
-- with an option to put the stock back) and 'service' (a straight revenue
-- reduction against a Visit or Inpatient case, no stock impact). Both reduce
-- revenue in the P&L for the month the refund itself was processed in —
-- not the original sale/visit's month — matching normal accounting practice.
CREATE TABLE IF NOT EXISTS refunds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_type TEXT NOT NULL CHECK (refund_type IN ('retail','service')),
    refund_date DATE NOT NULL,
    amount NUMERIC(12,3) NOT NULL,
    restocked BOOLEAN NOT NULL DEFAULT FALSE,   -- retail only: were the returned items put back into inventory?
    -- Retail only — which POS sale this refund is against. Required at
    -- the app layer (refund_retail_save() in app.py) so a retail refund
    -- can never be recorded against an item that was never actually
    -- sold, or for more than was sold minus what's already been
    -- refunded — see refund_items.sale_item_id for the per-line
    -- quantity/price tie-back.
    sale_id INTEGER,
    visit_id TEXT,                          -- service only, optional link
    inpatient_case_id INTEGER,              -- service only, optional link
    reason TEXT,
    -- How the money was actually handed back — 'Cash', 'Card', or
    -- 'Transfer' (same vocabulary as sales.payment_method). Not
    -- necessarily the same method the original sale/payment used; Cash
    -- Register needs this to know which bucket to subtract a refund from.
    refund_method TEXT,
    processed_by TEXT,
    created_at TEXT NOT NULL,
    FOREIGN KEY (sale_id) REFERENCES sales(id),
    FOREIGN KEY (visit_id) REFERENCES visits(id),
    FOREIGN KEY (inpatient_case_id) REFERENCES inpatient_cases(id)
);
CREATE INDEX IF NOT EXISTS idx_refunds_date ON refunds(refund_date);
CREATE INDEX IF NOT EXISTS idx_refunds_sale ON refunds(sale_id);

CREATE TABLE IF NOT EXISTS refund_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id INTEGER NOT NULL,
    item_id TEXT NOT NULL,
    quantity NUMERIC(10,3) NOT NULL,
    unit_price NUMERIC(12,3) NOT NULL,
    line_total NUMERIC(12,3) NOT NULL,
    -- The specific sale_items row this line is refunding against — lets
    -- refund_retail_save() price from what was actually charged (not
    -- today's Price List price) and sum prior refunds against this exact
    -- line to enforce a refund can never exceed what was actually sold.
    sale_item_id INTEGER,
    FOREIGN KEY (refund_id) REFERENCES refunds(id),
    FOREIGN KEY (item_id) REFERENCES inventory_list(id),
    FOREIGN KEY (sale_item_id) REFERENCES sale_items(id)
);
CREATE INDEX IF NOT EXISTS idx_refunditems_refund ON refund_items(refund_id);

