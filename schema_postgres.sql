-- VetClinicSystem JO database schema — v3 (PostgreSQL)
-- Ported from the original SQLite schema.sql. Table/column names, types,
-- and constraints are unchanged except: AUTOINCREMENT -> IDENTITY, and
-- REAL -> DOUBLE PRECISION (same practical behavior, more standard on PG).
--
-- Currency precision: unlike VetClinicSystem_IQ (Iraq — IQD's fils
-- subunit is practically obsolete, every real amount is a whole number,
-- so double-precision float loses nothing), the Jordanian Dinar is one
-- of three currencies worldwide (with KWD/BHD) that ISO 4217 assigns
-- 3 decimal places — the fils subunit is in everyday real use here,
-- and float64 cannot exactly represent most 3-decimal fractions
-- (0.1 + 0.2 != 0.3 in binary floating point). Every column that holds
-- a currency amount, or a quantity that gets multiplied directly
-- against one (so it must be the same numeric type to avoid a Python
-- Decimal/float TypeError — see parse_money() in app.py), is declared
-- NUMERIC here instead of DOUBLE PRECISION: NUMERIC(12,3) for money,
-- NUMERIC(10,3) for those quantities, NUMERIC(5,2) for discount_percent
-- (also multiplied directly against a money subtotal). Physical
-- measurements (weight_kg), inventory-count-only fields never
-- multiplied against a price (stock_counted, received_since_prior,
-- reorder_threshold, target_coverage_days, change_qty), and BCS stay
-- DOUBLE PRECISION/INTEGER — they're not currency and never mix with
-- Decimal arithmetic.

