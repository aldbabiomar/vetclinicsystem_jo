-- Manual bookkeeping for what a distributor has billed you and what
-- you've paid them — a lump-sum charge per bill, payments recorded
-- against it, balance always computed (never stored). Not linked to
-- inventory, POS, or any report; every bill is a manual entry, same as
-- the paper/memory tracking this replaces.
CREATE TABLE IF NOT EXISTS distributor_bills (
    id TEXT PRIMARY KEY,                 -- allocated via next_id(db, "DB")
    distributor_id TEXT NOT NULL,
    bill_date DATE NOT NULL,
    bill_reference TEXT,                 -- the distributor's own paper/invoice number, optional
