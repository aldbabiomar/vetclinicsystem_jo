    notes TEXT,
    created_at TEXT NOT NULL,
    created_by TEXT,
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    FOREIGN KEY (created_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_distbills_distributor ON distributor_bills(distributor_id);

CREATE TABLE IF NOT EXISTS distributor_bill_payments (
