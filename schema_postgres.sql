CREATE INDEX IF NOT EXISTS idx_consshrinkage_item ON consignment_shrinkage(item_id);
CREATE INDEX IF NOT EXISTS idx_consshrinkage_distributor ON consignment_shrinkage(distributor_id);

CREATE TABLE IF NOT EXISTS consignment_returns (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id TEXT NOT NULL,
