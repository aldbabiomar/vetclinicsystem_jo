CREATE INDEX IF NOT EXISTS idx_consreceipts_item ON consignment_receipts(item_id);
CREATE INDEX IF NOT EXISTS idx_consreceipts_distributor ON consignment_receipts(distributor_id);

CREATE TABLE IF NOT EXISTS consignment_shrinkage (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
